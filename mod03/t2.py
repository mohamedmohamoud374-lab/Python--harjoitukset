luokka = input("Anna hyttiluokka (LUX/A/B/C): ")
if luokka == "LUX":
    print("Parvekkeellinen hytti yläkannella.")
elif luokka == "A":
    print("Ikkunnallinen hyttu autokannen yläpuolella.")
elif luokka == "B":
    print("Ikkunaton hytti autokannen yläpuoella.")

elif luokka == "C":
    print("Ikkunaton hytti autokannen alapuolella.")
else:
    print("virheellinen hyttiluokka.")

    